-- Attach the changelog_trigger to the Brokkr-native Device table.
--
-- Context
-- -------
-- The original device-changelog trigger was created on 2025-06-17 by
-- 20250617205424_add_device_table_changelog_trigger against what was then
-- the "Device" table. On 2026-04-16, 20260416120000_rename_legacy_device
-- renamed that table to "LegacyDevice"; Postgres triggers follow renames,
-- so the trigger now sits on "LegacyDevice". The same-day netbox_port
-- migration (20260416200222_netbox_port) created a fresh "Device" table
-- — the new Brokkr-native model — with no trigger attached. Application
-- writes have since cut over entirely to prisma.device.*, so device row
-- changes have stopped being captured in Changelog.
--
-- This migration restores changelog coverage on the new "Device" table.
--
-- Function reuse (full-row capture is already guaranteed)
-- -------------------------------------------------------
-- changelog_trigger_func() is row-shape-agnostic by design — it uses
-- row_to_json(NEW)/row_to_json(OLD)::jsonb plus TG_TABLE_NAME, so the
-- full new Device row (status, role, hardware specs, network fields,
-- marketplace pricing, foreign keys, JSON columns — every column on the
-- row at the time of the write) is serialized verbatim into the
-- before / after / diff JSONB blobs. No function changes are required.
--
-- The function's v_pk_value::UUID cast continues to work because the new
-- Device.id is generated by Prisma's uuid() default — same shape as the
-- legacy table's id, which the trigger has been operating on without
-- issue since 2025-06.
--
-- The existing partial indexes on Changelog created by
-- 20250617205424_add_device_table_changelog_trigger —
--   idx_changelog_diff_is_listed_true / false
--   idx_changelog_diff_is_interruptible_true / false
-- key off (diff->>'isListed') and (diff->>'isInterruptible'); both flags
-- exist on the new Device model with identical names, so those indexes
-- will start catching events from the new Device automatically with no
-- index changes required.
--
-- Note on secrets
-- ---------------
-- Full-row capture by row_to_json() includes every column on Device,
-- including monitorPsk (the monitoring pre-shared key). This matches the
-- pre-existing posture on the legacy table — the trigger has captured
-- equivalent fields there since 2025-06 — so this migration does not
-- change the secret-redaction model. If we ever decide to redact PSKs
-- and similar from Changelog, that's a function-level change to
-- changelog_trigger_func() and should be applied to LegacyDevice in the
-- same migration to keep the two consistent.
--
-- Scope note
-- ----------
-- The trigger only catches FUTURE writes. There is no backfill of
-- change events for the gap between the netbox_port merge and this
-- migration.

CREATE OR REPLACE TRIGGER changelog_trigger
    AFTER INSERT OR UPDATE OR DELETE ON "Device"
    FOR EACH ROW EXECUTE FUNCTION changelog_trigger_func();
