const TITLE_INNER = 55;

function bandRow(title: string): string {
  const label = `■  ${title}  ■`;
  const text = label.length > TITLE_INNER ? label.slice(0, TITLE_INNER) : label;
  const pad = TITLE_INNER - text.length;
  const left = Math.floor(pad / 2);
  return `  ║${' '.repeat(left)}${text}${' '.repeat(pad - left)}║`;
}

