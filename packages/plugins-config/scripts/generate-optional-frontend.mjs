#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(pkgRoot, 'package.json'), 'utf8'));

function exportName(pkgName) {
  const camel = pkgName.replace(/^@hydrahost\/plugin-/, '').replace(/-([a-z])/g, (_, c) => c.toUpperCase());
  return `${camel}FrontendManifest`;
}

const found = [];
for (const dep of Object.keys(pkg.optionalDependencies ?? {})) {
  if (!dep.startsWith('@hydrahost/plugin-')) continue;
  try {
    import.meta.resolve(`${dep}/frontend-manifest`);
  } catch {
    continue;
  }
  found.push({ pkg: dep, name: exportName(dep) });
}

// Sorted only to keep the emitted file stable; the user-visible rail order is SIDEBAR_ORDER in src/frontend.ts.
found.sort((a, b) => a.pkg.localeCompare(b.pkg));

const header = `// GENERATED by scripts/generate-optional-frontend.mjs — DO NOT EDIT, DO NOT COMMIT.
// Frontend manifests for the optional plugins this tree installs; empty where none are present.\n`;

const imports = found.map((f) => `import { ${f.name} } from '${f.pkg}/frontend-manifest';`).join('\n');
const list = found.map((f) => f.name).join(', ');
const body = `${imports ? `${imports}\n` : ''}import type { PluginFrontendManifest } from '@hydrahost/plugin-sdk';

export const optionalFrontendManifests: PluginFrontendManifest[] = [${list}];\n`;

writeFileSync(join(pkgRoot, 'src', 'optional-frontend.generated.ts'), `${header}\n${body}`);
console.log(
  `generate-optional-frontend: ${found.length} optional frontend plugin(s) [${found.map((f) => f.pkg).join(', ') || 'none'}]`,
);
